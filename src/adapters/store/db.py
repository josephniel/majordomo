"""Async Postgres client for the memory layer — one implementation of MemoryStore.

One MemoryDatabase per persona container (one connection pool per process).
On startup, init_schema() applies the idempotent schema. Recall is hybrid:
Postgres FTS (`tsvector`) + trigram + local semantic embeddings (pgvector
cosine). Embeddings are generated by a local model (see .embeddings), so
recall stays provider-independent.

This class satisfies `ports.MemoryStore` STRUCTURALLY — it does not inherit
from it, and nothing checks at import time. That is the point of a structural
port: an alternative store owes the same methods, not a base class. What it
does owe beyond the signatures is the scoring contract in `ports/memory.py`
(scores in [0, 1], comparable across queries), which the type system cannot
state and `evals/recall_cases.yaml` measures instead.

The extra methods here — init_schema, backfill_embeddings, fetch — are
deliberately NOT on the port. They are this backend's maintenance surface and
only the composition root calls them.
"""
